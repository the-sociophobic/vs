const DEFAULT_RATIO = { w: 487, h: 242 }

function parseRatio(ratio) {
  if (!ratio || typeof ratio !== 'string') return DEFAULT_RATIO
  const [w, h] = ratio.split('x').map(Number)
  if (!w || !h) return DEFAULT_RATIO
  return { w, h }
}

